
namespace HomeFitBot
{
    public class Program
    {
        // Константа с версией программы. Значение подставляется в вызывающий код на этапе компиляции.
        const string Version = "1.0.0";

        // Константа с названием бота. Значение подставляется в вызывающий код на этапе компиляции.
        const string BotName = "HomeFitBot";

        // Статическое поле дата создания программы. Значение задаётся один раз при инициализации типа.
        static readonly DateTime CreatedAt = new DateTime(2026, 10, 03);

        // Статическое поле с текущим именем пользователя.
        static string _userName;

        // Статическое вычисляемое свойство префикс.
        // Возвращает "Имя, " если пользователь представился, иначе пустую строку. Убирает дублирование строк в обработчиках.
        // Выражение => означает, что геттер вычисляется при каждом обращении и заново строит строку по текущему значению _userName.
        static string Prefix => _userName != null ? $"{_userName}, " : "";

        static void Main()
        {
            // Вызываем метод, который выводит в консоль приветственное сообщение и список доступных команд.
            PrintWelcome();

            // Бесконечный цикл while: выход выполняется через break.
            while (true)
            {
                // Приглашение к вводу без перевода строки.
                Console.Write("> ");

                // Читаем введённую строку.
                var input = Console.ReadLine();

                // Если ReadLine вернул null, корректно выходим из цикла.
                if (input == null) break;

                // Передаём введенную строку без пробелов по краям в обработчик HandleCommand. Trim() убирает пробелы по краям.
                // Если метод вернул true (команда /exit), тогда завершаем цикл.
                if (HandleCommand(input.Trim()))
                    break;
            }


            /// <summary>
            /// Метод PrintWelcome выводит приветствие и перечень доступных команд.
            /// </summary>
            static void PrintWelcome()
            {
                // Приветственная строка.
                Console.WriteLine("Добро пожаловать в фитнес-бот для домашних тренировок!");

                // Подсказка со списком доступных команд.
                Console.WriteLine("Доступные команды: /start, /help, /info, /exit");
            }


            /// <summary>
            /// Метод HandleCommand — это центральный разборщик команд, который выполняет функцию диспетчеризации. 
            /// Данный метод разбирает строку на команду и аргумент, и вызывает нужный обработчик.
            /// </summary>
            /// <param name="input"> Введенная строка </param>
            /// <returns> Возвращает true, если работу программы нужно завершить (/exit), и false во всех остальных случаях. </returns>
            static bool HandleCommand(string input)
            {
                // Если пустой ввод — игнорируем, возвращаем false и продолжаем цикл.
                if (input.Length == 0) return false;

                // Ищем позицию первого пробела, разделяющего команду и аргумент.
                // IndexOf возвращает -1, если пробела нет (команда без аргументов).
                var space = input.IndexOf(' ');

                // Тернарный оператор выбирает способ разбора: если пробела нет — вся строка является командой, иначе команда — это часть строки до первого пробела.
                var command = space < 0 ? input : input.Substring(0, space);

                // Тернарный оператор выбирает способ разбора аргумента: если пробела нет — пустая строка,
                // иначе берём всё после пробела и с помощью Trim() обрезаем пробелы.
                var argument = space < 0 ? string.Empty : input.Substring(space + 1).Trim();

                // switch по команде, приведённой к нижнему регистру.
                // ToLowerInvariant() использует инвариантную культуру — не зависит от локали, что важно для команд.
                // Благодаря этому, например, введенные команды "/HELP", "/Help" и "/help" обрабатываются одинаково.
                switch (command.ToLowerInvariant())
                {
                    // Каждый case вызывает соответствующий обработчик и делегирует обработку отдельному методу. break выходит из switch.

                    // Команда "Старт". Запрашивает и сохраняет имя пользователя.
                    case "/start":
                        HandleStart();
                        break;

                    // Команда "Справка". Выводит список доступных команд.
                    case "/help":
                        HandleHelp();
                        break;

                    // Команда "Информация о программе". Выводит название, версию и дату создания.
                    case "/info":
                        HandleInfo();
                        break;

                    // Команда "/echo" повторяет введённый текст пользователем.
                    // Здесь передаётся "разобранный" аргумент, а не "сырая" строка — обработчик уже не занимается парсингом.
                    case "/echo":
                        HandleEcho(argument);
                        break;

                    // Команда "Выход из программы". Выводит прощание в консоль и сразу возвращает true — сигнал завершения для Main.
                    // return выходит и из switch, и из метода, поэтому break не нужен.
                    case "/exit":
                        HandleExit();
                        return true;

                    // Ветка по умолчанию, выполняется если команда не распознана (неизвестная команда).
                    default:

                        // Тернарный оператор выбирает строку с сообщением об ошибке: 
                        // если известно имя пользователя - персонализированное сообщение об ошибке, иначе нейтрально сообщение об ошибке.
                        Console.WriteLine(_userName != null
                            ? $"{_userName}, неизвестная команда. Введите /help"
                            : "Неизвестная команда. Введите /help");

                        // Выход из switch, метод вернёт false ниже.
                        break;
                }

                // Все команды, кроме /exit, после обработки доходят сюда. По умолчанию программа продолжает работу.
                return false;
            }


            /// <summary>
            /// Метод HandleStart запрашивает имя пользователя и сохраняет его в статическое поле класса _userName.
            /// </summary>
            static void HandleStart()
            {
                // Приглашение ввести имя пользователя.
                Console.Write("Введите ваше имя: ");

                // Читаем введенное имя пользователя.
                var name = Console.ReadLine();

                // Проверяем, что строка не null и не состоит только из пробелов.
                if (string.IsNullOrWhiteSpace(name))
                {
                    // Сообщаем об ошибке и выходим из метода.
                    Console.WriteLine("Имя не может быть пустым или состоять только из пробелов. Попробуйте снова.");

                    return;
                }

                // Сохраняем имя пользователя без пробелов по краям в статическое поле класса _userName.
                _userName = name.Trim();

                // Подтверждение успешной регистрации с обращением по имени пользователя.
                Console.WriteLine($"Приятно познакомиться, {_userName}!");
            }


            /// <summary>
            /// Метод HandleHelp выводит справочную информацию со списком доступных команд.
            /// </summary>
            static void HandleHelp()
            {
                // Заголовок с префиксом. Prefix автоматически добавляет "Имя, " при наличии имени пользователя.
                Console.WriteLine($"{Prefix}список доступных команд:");

                // Описание команды /start.
                Console.WriteLine("  /start — регистрация пользователя в системе. Необходимо представиться (ввести своё имя).");

                // Описание команды /help.
                Console.WriteLine("  /help  — справочная информация.");

                // Описание команды /info.
                Console.WriteLine("  /info  — версия и дата создания программы.");

                // Описание команды /echo с пометкой о доступности после /start.
                Console.WriteLine("  /echo <текст> — повторить текст (доступно после /start).");

                // Описание команды /exit.
                Console.WriteLine("  /exit  — выход из программы.");
            }
        }
    }
}